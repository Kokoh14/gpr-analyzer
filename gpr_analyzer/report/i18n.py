class Translator:
    """t(key) for labels, paras(key) for paragraphs. Missing keys fall back to the key itself."""

    def __init__(self, lang: str = "bi") -> None:
        if lang not in LANGS:
            raise ValueError(f"lang must be one of {LANGS}, got {lang!r}")
        self.lang = lang

    def _one(self, key: str, lang: str, params: dict[str, Any]) -> str:
        entry = STRINGS.get(key)
        if entry is None:
            return key
        return entry.get(lang, entry["en"]).format(**params)

    def t(self, key: str, **params: Any) -> str:
        if self.lang == "bi":
            th, en = self._one(key, "th", params), self._one(key, "en", params)
            return th if th == en else f"{th} / {en}"
        return self._one(key, self.lang, params)

    def paras(self, key: str, **params: Any) -> list[str]:
        if self.lang == "bi":
            th, en = self._one(key, "th", params), self._one(key, "en", params)
            return [th] if th == en else [th, en]
        return [self._one(key, self.lang, params)]

    def has(self, key: str) -> bool:
        return key in STRINGS
